    text(d.cond, 12 * s, H - 36 * s, Font.boldSystemFont(13 * s), .98, 'left', W - 24 * s); text(hl, 12 * s, H - 20 * s, Font.systemFont(11 * s), .85, 'left', W - 24 * s);
