function clamp(v, a, b) { return Math.max(a, Math.min(b, v)); }
function mixRgb(a, b, t) { return [Math.round(a[0] + (b[0] - a[0]) * t), Math.round(a[1] + (b[1] - a[1]) * t), Math.round(a[2] + (b[2] - a[2]) * t)]; }
/** The sky colour at t (0 top, 1 bottom) between the stops of skyStops(): [r, g, b] */
function skyAt(stops, t) {
  if (stops.length < 2) return stops[0];
  const f = clamp(t, 0, 1) * (stops.length - 1), i = Math.min(stops.length - 2, Math.floor(f));
  return mixRgb(stops[i], stops[i + 1], f - i);
}
function fmtTemp(v) { if (v == null || isNaN(v)) return '–'; return String(Math.round(v)); }
/** Which weather entity to use: the wanted one if it exists, else the usual ones (weather.forecast_home, weather.home), else the first one there is. states: [{ entity_id }] */
function pickWeather(states, want) {
  const ids = (states || []).map(x => x && x.entity_id).filter(id => /^weather\./.test(String(id || ''))).sort();
  if (want && ids.indexOf(want) >= 0) return want;
  for (const id of ['weather.forecast_home', 'weather.home']) if (ids.indexOf(id) >= 0) return id;
  return ids[0] || null;
}
/** About how wide a thin number is at `size` (Scriptable cannot measure text) */
function numWidth(str, size) { let w = 0; for (const ch of String(str)) w += size * (ch === '1' ? .36 : (ch === '°' ? .36 : .53)); return w; }

/** What the widget shows, from the weather state, the sun, and the two forecasts: { name, temp, state, cond, night, kind, hi, lo, hours, days, rows } */
function summarize(data, lang) {
  const st = data && data.st, a = (st && st.attributes) || {}, sun = data && data.sun, now = Date.now();
  const hour = new Date().getHours(), night = isNight(sun && sun.state, st && st.state, hour);
  const fmtT = iso => { const d = new Date(iso); return isNaN(d) ? '' : d.toLocaleTimeString(lang, { hour: 'numeric', minute: '2-digit' }); };
  const fmtH = t => new Date(t).toLocaleTimeString(lang, { hour: 'numeric' });
  const days = dayItems((data && data.daily) || [], lang, 6), hours = hourItems((data && data.hourly) || [], now, lang, fmtH, 6);
  const d0 = ((data && data.daily) || [])[0] || {};
  return {
    name: placeName(a.friendly_name || 'Weather'), unavailable: !st || st.state === 'unavailable' || st.state === 'unknown',
    temp: a.temperature != null ? Math.round(a.temperature) : null, state: st ? st.state : 'unavailable', cond: st ? condText(lang, st.state) : '–', night: night,
    kind: iconKind(st ? st.state : 'cloudy', night), hi: d0.temperature != null ? Math.round(d0.temperature) : null, lo: d0.templow != null ? Math.round(d0.templow) : null,
    hours: hours, days: days, rows: detailRows(a, sun && sun.attributes, null, lang, fmtT),
  };
}

