  push('humidity', at.humidity != null ? num(at.humidity) + '%' : null);
  if (at.wind_speed != null) push('wind', num(at.wind_speed) + ' ' + (at.wind_speed_unit || '') + (compass(at.wind_bearing) ? ' ' + compass(at.wind_bearing) : ''));
