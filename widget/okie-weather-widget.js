/** The weather and its forecasts, or the last ones seen (marked old) when Home Assistant cannot be reached. A weather entity that does not exist is looked for in the list of states. */
async function load(cfg) {
  try {
    let st = null;
    try { st = await api(cfg, '/api/states/' + cfg.entity); } catch (e) { st = null; }
    if (!st || !st.attributes) {
      const all = await api(cfg, '/api/states'), pick = pickWeather(all, cfg.entity);
      if (!pick) throw new Error('Home Assistant has no weather entity');
      cfg.entity = pick; Keychain.set(KEY.entity, pick);
      st = await api(cfg, '/api/states/' + pick);
      if (!st || !st.attributes) throw new Error('unexpected answer');
    }
    let sun = null; try { sun = await api(cfg, '/api/states/sun.sun'); } catch (e) { /* the hour tells the night */ }
    const [daily, hourly] = await Promise.all([forecast(cfg, 'daily'), forecast(cfg, 'hourly')]);
    const data = { st: st, sun: sun, daily: daily, hourly: hourly, at: Date.now() };
    Keychain.set(KEY.last + '_' + cfg.entity, JSON.stringify(data));
    return { data: data, old: false };
  } catch (e) {
    const last = keep(KEY.last + '_' + cfg.entity);
    if (last) { try { return { data: JSON.parse(last), old: true, error: String(e && e.message || e) }; } catch (x) { /* nothing usable */ } }
    return { data: { st: null }, old: true, error: String(e && e.message || e) };
  }
}

