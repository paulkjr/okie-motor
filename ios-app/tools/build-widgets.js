#!/usr/bin/env node
// Turns widgets/widgets.json (the one place where the widgets' look and defaults are written down) into Swift: Shared/WidgetSpec.swift.
// Usage: node tools/build-widgets.js        (tools/build.sh runs it for you)
'use strict';
const fs = require('fs'), path = require('path');
const spec = JSON.parse(fs.readFileSync(path.join(__dirname, '../Widgets/widgets.json'), 'utf8'));
const isColor = v => typeof v === 'string' && /^#[0-9a-fA-F]{6}$/.test(v);
const hex = v => '0x' + v.slice(1).toLowerCase();
const cap = s => s[0].toUpperCase() + s.slice(1);
const swiftType = v => typeof v === 'number' ? 'CGFloat' : typeof v === 'boolean' ? 'Bool' : isColor(v) ? 'UInt32' : 'String';
const swiftVal = v => typeof v === 'number' ? String(v) : typeof v === 'boolean' ? String(v) : isColor(v) ? hex(v) : JSON.stringify(v);
const pad = n => '    '.repeat(n);

function structFor(name, sample, ind) {
  let s = `${pad(ind)}struct ${name} {\n`;
  for (const k of Object.keys(sample)) s += `${pad(ind + 1)}let ${k}: ${swiftType(sample[k])}\n`;
  return s + `${pad(ind)}}\n`;
}
function inst(obj, ind) { return Object.keys(obj).map(k => `${k}: ${swiftVal(obj[k])}`).join(', '); }

function emit(obj, ind) {
  let s = '';
  for (const k of Object.keys(obj)) {
    if (k.startsWith('_')) continue;
    const v = obj[k];
    if (k === 'layoutSet') {
      const names = Object.keys(v);
      s += structFor('Layout', v[names[0]], ind);
      for (const n of names) s += `${pad(ind)}static let ${n} = Layout(${inst(v[n])})\n`;
    } else if (Array.isArray(v)) {
      if (v.length && typeof v[0] === 'object') {
        const sn = cap(k.replace(/s$/, ''));
        s += structFor(sn, v[0], ind);
        s += `${pad(ind)}static let ${k}: [${sn}] = [\n${v.map(o => `${pad(ind + 1)}${sn}(${inst(o)}),`).join('\n')}\n${pad(ind)}]\n`;
      } else if (v.length && isColor(v[0])) s += `${pad(ind)}static let ${k}: [UInt32] = [${v.map(hex).join(', ')}]\n`;
      else s += `${pad(ind)}static let ${k}: [String] = [${v.map(x => JSON.stringify(x)).join(', ')}]\n`;
    } else if (v && typeof v === 'object') {
      s += `${pad(ind)}enum ${cap(k)} {\n${emit(v, ind + 1)}${pad(ind)}}\n`;
    } else s += `${pad(ind)}static let ${k}: ${swiftType(v)} = ${swiftVal(v)}\n`;
  }
  return s;
}
const out = '// Generated by tools/build-widgets.js from widgets/widgets.json. Do not edit: change the json and run tools/build.sh.\nimport CoreGraphics\n\nenum WidgetSpec {\n' + emit(spec, 1) + '}\n';
fs.writeFileSync(path.join(__dirname, '../Shared/WidgetSpec.swift'), out);
console.log('Shared/WidgetSpec.swift written');
