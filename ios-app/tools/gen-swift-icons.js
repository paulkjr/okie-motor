#!/usr/bin/env node
// Turns the icon table of the Okie Motor card (okie-motor/src/okie-ui.js, 24 x 24 line icons) into Swift: Shared/OkieSVGIcons.swift.
// Usage: node tools/gen-swift-icons.js
'use strict';
const fs = require('fs'), path = require('path');
const src = fs.readFileSync(path.join(__dirname, '../../src/okie-ui.js'), 'utf8');
const a = src.indexOf('var ICONS = {'), b = src.indexOf('\n  };', a);
const S = x => x;
const icons = eval('(' + src.slice(a + 'var ICONS = '.length, b + 4) + ')');
const attr = (tag, name) => { const m = new RegExp('\\s' + name + '="([^"]*)"').exec(tag); return m ? m[1] : null; };
const q = s => JSON.stringify(s);
const num = (v, d = 0) => (v == null ? d : +v);
let out = '// Generated by tools/gen-swift-icons.js from okie-motor/src/okie-ui.js. Do not edit.\nimport Foundation\n\nextension OkieSVG {\n    static let icons: [String: [Prim]] = [\n';
for (const name of Object.keys(icons).sort()) {
  const prims = [];
  for (const tag of icons[name].match(/<(path|rect|circle)\b[^>]*>/g) || []) {
    const kind = /^<(\w+)/.exec(tag)[1];
    let p;
    if (kind === 'path') p = `.path(${q(attr(tag, 'd'))})`;
    else if (kind === 'rect') p = `.rect(x: ${num(attr(tag, 'x'))}, y: ${num(attr(tag, 'y'))}, w: ${num(attr(tag, 'width'))}, h: ${num(attr(tag, 'height'))}, r: ${num(attr(tag, 'rx'))})`;
    else p = `.circle(cx: ${num(attr(tag, 'cx'))}, cy: ${num(attr(tag, 'cy'))}, r: ${num(attr(tag, 'r'))})`;
    const sw = attr(tag, 'stroke-width'), fill = attr(tag, 'fill'), stroke = attr(tag, 'stroke');
    prims.push(`Prim(${p}${sw ? `, strokeWidth: ${sw}` : ''}${fill ? `, fill: ${q(fill)}` : ''}${stroke ? `, stroke: ${q(stroke)}` : ''})`);
  }
  out += `        ${q(name)}: [${prims.join(', ')}],\n`;
}
out += '    ]\n';
// the card's weather pictures (okie-weather.js ICON_INNER: cloud, sun, moon, rain)
const wsrc = fs.readFileSync(path.join(__dirname, '../../src/okie-weather.js'), 'utf8');
const wa = wsrc.indexOf('var ICON_INNER = {'), wb = wsrc.indexOf('\n  };', wa);
const wicons = eval('(' + wsrc.slice(wa + 'var ICON_INNER = '.length, wb + 4) + ')');
out += '    static let weatherIcons: [String: [Prim]] = [\n';
for (const name of Object.keys(wicons).sort()) {
  const prims = [];
  for (const tag of wicons[name].match(/<(path|circle)\b[^>]*>/g) || []) {
    const kind = /^<(\w+)/.exec(tag)[1];
    prims.push(kind === 'path' ? `Prim(.path(${q(attr(tag, 'd'))}))` : `Prim(.circle(cx: ${num(attr(tag, 'cx'))}, cy: ${num(attr(tag, 'cy'))}, r: ${num(attr(tag, 'r'))}))`);
  }
  out += `        ${q(name)}: [${prims.join(', ')}],\n`;
}
out += '    ]\n}\n';
fs.writeFileSync(path.join(__dirname, '../Shared/OkieSVGIcons.swift'), out);
console.log(Object.keys(icons).length + ' icons written');
