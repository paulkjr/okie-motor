#!/usr/bin/env node
// Builds Resources/BigThermostat.html: the thermostat's controls as one page the app shows in a web view when a widget opens the thermostat: the round menu bubble (Controls, Context, History,
// Schedule, Settings), the wheel at the right edge, the number, the modes, hold to turn off. It is the SAME page the Scriptable widget uses (okie-motor/widget/big-page.html with the card's fonts and
// the card's own history / schedule / dial code, put together by okie-motor/tools/make-widget.py), so a change there reaches both. The page is left with three holes for the app to fill when it
// opens it: __CFG__ (address, token, entity), __LOOK__ and __STORE__ (the saved dial look and profiles).
// Usage: node tools/build-big-page.js        (tools/build.sh runs it for you)
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');

const src = fs.readFileSync(path.join(__dirname, '../../widget/okie-thermostat-widget.js'), 'utf8');
const A = '// ---- generated by tools/make-widget.py', Z = '// ---- end generated ----';
const a = src.indexOf(A), z = src.indexOf(Z);
if (a < 0 || z < 0) throw new Error('the generated block is missing in okie-thermostat-widget.js (run okie-motor/tools/make-widget.py)');
const gen = new Function(src.slice(a, z) + '\nreturn { FONT_CSS, LOGIC_SRC, SCHED_SRC, LOOK_SRC, BIG_PAGE };')();

// the colour code the page shares with the widget: the very functions of the script (the page gets their source text)
const main = src.slice(0, a);
const ctx = vm.createContext({ console });
const shared = vm.runInContext(main + '\n;({ fns: [clamp, hexRgb, mix, toF, colorFor, fmtTemp, summarize, modeIcons].map(f => f.toString()), MODES })', ctx);

const boot = 'var CFG = __CFG__;\nvar LOOK = __LOOK__, MODES = ' + JSON.stringify(shared.MODES) + ', STORE = __STORE__;';
let page = gen.BIG_PAGE;
const fill = (mark, text) => { if (page.split(mark).length !== 2) throw new Error('mark ' + mark + ' not found exactly once'); page = page.replace(mark, () => text); };
fill('/*@FONTS@*/', gen.FONT_CSS);
fill('/*@BOOT@*/', boot);
fill('/*@SHARED@*/', shared.fns.join('\n'));
fill('/*@LOGIC@*/', gen.LOGIC_SRC);
fill('/*@SCHED@*/', gen.SCHED_SRC);
fill('/*@LOOKSRC@*/', gen.LOOK_SRC);

// the page fills the whole screen (the bubble at the very top, as in the card); the app's "Close" sits on the bubble's row, at the left, so nothing is added to the page itself

const out = path.join(__dirname, '../Resources/BigThermostat.html');
fs.writeFileSync(out, page);
console.log('big thermostat page: ' + out + ' (' + Math.round(page.length / 1024) + ' KB)');
