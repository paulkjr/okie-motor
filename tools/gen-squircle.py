#!/usr/bin/env python3
"""Regenerate src/okie-squircle.js from the extracted FSC presets.

Source: ../fsc-analysis/fsc-squircle-presets.json (taken from Fast-Search-Card
v1.1.2480). Run from anywhere: python3 tools/gen-squircle.py
"""
import json
import pathlib

here = pathlib.Path(__file__).resolve().parent.parent
src = here.parent / "fsc-analysis" / "fsc-squircle-presets.json"
d = json.loads(src.read_text())

polys = {
    "none": "none",
    "soft": d["polygons"]["subtle"],
    "standard": d["polygons"]["balanced"],
    "strong": d["polygons"]["prominent"],
}
params = {
    "soft": d["presets"]["subtle"],
    "standard": d["presets"]["balanced"],
    "strong": d["presets"]["prominent"],
}

TEMPLATE = """/* okie-squircle: FSC's four card shapes as CSS clip-path polygons.
 * GENERATED by tools/gen-squircle.py from fsc-analysis/fsc-squircle-presets.json
 * (extracted from Fast-Search-Card v1.1.2480, GPL-3.0-or-later). Do not edit by hand.
 * none | soft (=subtle) | standard (=balanced) | strong (=prominent)
 */
(function (g) {
  'use strict';
  var SQUIRCLES = %s;
  var PARAMS = %s;
  var api = { SQUIRCLES: SQUIRCLES, PARAMS: PARAMS, names: ['none', 'soft', 'standard', 'strong'],
    clipPath: function (name) { return SQUIRCLES[name] || 'none'; } };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else { g.OkieMotor = g.OkieMotor || {}; g.OkieMotor.squircle = api; }
})(typeof globalThis !== 'undefined' ? globalThis : window);
"""
out = TEMPLATE % (json.dumps(polys, indent=2), json.dumps(params))
(here / "src" / "okie-squircle.js").write_text(out)
print("wrote", here / "src" / "okie-squircle.js", len(out), "bytes")
