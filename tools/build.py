#!/usr/bin/env python3
"""Build the Okie Motor.

    python3 tools/build.py            write dist/okie-motor.js, dist/okie-version.json and dist/okie-install.py
                                      (and, when a Hemma git clone sits next to this folder, the bundle into it)
    python3 tools/build.py --build N  pin the build stamp (reproducible output, used by tests)
    python3 tools/build.py --no-hemma ignore a Hemma clone and use the committed hemma/edits.json

The installer edits Hemma with exact-anchor edits. They are derived from `git diff` of a Hemma clone when one is
available (and then saved to hemma/edits.json); without a clone the saved file is used, so the repo builds on its own.

Why one bundle: Home Assistant loads dashboard resources in parallel, so scripts that depend on each
other cannot rely on load order. One ordered file removes the problem. The order is the <script>
order of harness/index.html, so the browser harness and the shipped bundle never disagree.
"""
import argparse
import base64
import datetime
import json
import os
import pathlib
import re
import subprocess
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEMMA = pathlib.Path(os.environ.get("HEMMA_DIR") or ROOT.parent / "Hemma")
SCRIPTS = HEMMA / "custom_components/hemma/scripts"
DIST = ROOT / "dist"
EDITS_FILE = ROOT / "hemma/edits.json"


def module_order():
    html = (ROOT / "harness/index.html").read_text()
    order = re.findall(r'<script src="\.\./src/(okie-[a-z-]+\.js)"></script>', html)
    missing = [m for m in order if not (ROOT / "src" / m).exists()]
    if missing:
        sys.exit("harness lists modules that do not exist: %s" % missing)
    unlisted = sorted(p.name for p in (ROOT / "src").glob("okie-*.js") if p.name not in order)
    if unlisted:
        sys.exit("src modules missing from harness/index.html (and so from the bundle): %s" % unlisted)
    return order


def make_bundle(version, build):
    parts = []
    for name in module_order():
        parts.append("\n/* ---- %s ---- */\n%s" % (name, (ROOT / "src" / name).read_text()))
    head = (
        "/* Okie Motor v%s (build %s): FSC-style search, bento start, detail views, apps and rest mode for Hemma.\n"
        " * One ordered bundle of src/okie-*.js, generated by tools/build.py. Do not edit; edit src/ and rebuild.\n"
        " * Squircle shape presets are derived from Fast Search Card (GPL-3.0-or-later); see README. */\n"
        "(function () {\n'use strict';\n"
        "if (typeof globalThis.__okieMotorLoaded !== 'undefined') return;   // loaded twice: do nothing\n"
        "globalThis.__okieMotorLoaded = true;\n"
        "globalThis.OkieMotor = globalThis.OkieMotor || {};\n"
        "globalThis.OkieMotor.version = %s;\nglobalThis.OkieMotor.build = %s;\n"
        "globalThis.OkieMotor.versionUrl = '/hemma_scripts/okie-version.json';\n"
        % (version, build, json.dumps(version), build)
    )
    return head + "".join(parts) + "\n})();\n"


def git(*args):
    return subprocess.run(["git", "-C", str(HEMMA)] + list(args), check=True, capture_output=True, text=True).stdout


def hunks_to_edits(rel, name, group):
    """Turn `git diff HEAD` hunks of a file into exact-anchor edits (context + removed -> context + added)."""
    diff = git("diff", "-U3", "--no-color", "HEAD", "--", rel)
    edits, cur = [], None
    for line in diff.splitlines(keepends=True):
        if line.startswith("@@"):
            if cur:
                edits.append(cur)
            cur = {"old": [], "new": []}
        elif cur is None or line.startswith("\\ No newline"):
            continue
        elif line.startswith("+"):
            cur["new"].append(line[1:])
        elif line.startswith("-"):
            cur["old"].append(line[1:])
        elif line.startswith(" "):
            cur["old"].append(line[1:]); cur["new"].append(line[1:])
    if cur:
        edits.append(cur)
    return [{"file": rel, "name": "%s #%d" % (name, i + 1), "group": group, "old": "".join(e["old"]), "new": "".join(e["new"])} for i, e in enumerate(edits)]


TEMPLATES = "custom_components/hemma/panel/hemma-templates.json"
T_ANCHOR = '{"border-radius":"var(--hemma-tile-radius, var(--ha-card-border-radius, 28px))"},{"box-shadow":"var(--hemma-box-shadow-mq) !important"}'
T_ADD = '{"clip-path":"var(--hemma-tile-clip-path, none)"},{"-webkit-clip-path":"var(--hemma-tile-clip-path, none)"},'


def edits_from_clone():
    edits = []
    edits += hunks_to_edits("custom_components/hemma/const.py", "register okie-motor.js", "motor")
    edits += hunks_to_edits("custom_components/hemma/scripts/hemma-core.js", "desktop nav glass + scrollbar", "look")
    edits += hunks_to_edits("themes/hemma/hemma.yaml", "squircle token + hero retune", "look")
    edits.append({"file": TEMPLATES, "name": "tile clip-path", "group": "look", "old": T_ANCHOR, "new": T_ANCHOR.replace('{"box-shadow"', T_ADD + '{"box-shadow"', 1)})
    return edits


def make_edits(use_clone):
    if use_clone:
        edits = edits_from_clone()
        EDITS_FILE.parent.mkdir(exist_ok=True)
        EDITS_FILE.write_text(json.dumps(edits, indent=1, ensure_ascii=False) + "\n")
        return edits
    if not EDITS_FILE.exists():
        sys.exit("no Hemma clone next to this folder (set HEMMA_DIR) and no hemma/edits.json to fall back on")
    return json.loads(EDITS_FILE.read_text())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", type=int)
    ap.add_argument("--no-hemma", action="store_true")
    args = ap.parse_args()
    use_clone = (not args.no_hemma) and (HEMMA / ".git").exists()
    version = json.loads((ROOT / "package.json").read_text())["version"]
    build = args.build or int(datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d%H%M%S"))

    bundle = make_bundle(version, build)
    vjson = json.dumps({"version": version, "build": build}) + "\n"
    DIST.mkdir(exist_ok=True)
    (DIST / "okie-motor.js").write_text(bundle)
    (DIST / "okie-version.json").write_text(vjson)
    if use_clone:
        SCRIPTS.mkdir(parents=True, exist_ok=True)
        (SCRIPTS / "okie-motor.js").write_text(bundle)
        (SCRIPTS / "okie-version.json").write_text(vjson)

    z = lambda s: base64.b64encode(zlib.compress(s.encode("utf-8"), 9)).decode("ascii")
    payload = {"version": version, "build": build, "files": {"okie-motor.js": z(bundle), "okie-version.json": z(vjson)}, "edits": make_edits(use_clone)}
    blob = base64.b64encode(zlib.compress(json.dumps(payload).encode("utf-8"), 9)).decode("ascii")
    out = DIST / "okie-install.py"
    out.write_text((ROOT / "tools/installer_template.py").read_text().replace("__PAYLOAD__", blob))
    out.chmod(0o755)
    print("bundle   %s  (%d bytes)%s" % (DIST / "okie-motor.js", len(bundle.encode()), "  + copied into the Hemma clone" if use_clone else ""))
    print("version  %s build %s" % (version, build))
    print("edits    %d  (%s)" % (len(payload["edits"]), ", ".join(sorted({e["group"] for e in payload["edits"]}))))
    print("installer %s  (%d bytes)" % (out, out.stat().st_size))


if __name__ == "__main__":
    main()
