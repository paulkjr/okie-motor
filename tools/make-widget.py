#!/usr/bin/env python3
"""Build widget/okie-thermostat-widget.js: put the big thermostat page, the card's fonts and the card's own history code into it.

    python3 tools/make-widget.py

The widget is one file the iPhone gets by itself. What goes in, between the two marker lines at the end of the script:
  FONT_CSS   Sora and Manrope (SIL Open Font License 1.1, see NOTICE.md) from src/okie-thermo-fonts.js
  LOOK_SRC   the card's dial look maths (defaults, normalizing, glow shape, tick count) from src/okie-thermo.js, so the Dial look settings mean exactly the same
  SCHED_SRC  the card's thermostat schedule code (reading and building the Scheduler's actions, the profiles) from src/okie-thermo-sched.js
  LOGIC_SRC  the card's history functions (toSegments, historyStats, hourlyActivity, ...) cut out of src/okie-logic.js, so the History tab counts exactly like the card
  BIG_PAGE   widget/big-page.html, the full-screen thermostat with its five tabs
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent


def function_source(text, name):
    m = re.search(r"^  function %s\(" % re.escape(name), text, re.M)
    assert m, "function %s not found in src/okie-logic.js" % name
    i = text.index("{", m.start())
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[m.start():j + 1]
    raise AssertionError("unbalanced braces in " + name)


fonts = (ROOT / "src/okie-thermo-fonts.js").read_text(encoding="utf-8")
faces = re.findall(r"@font-face\{.*?\}", fonts)
assert len(faces) == 2, "expected the two font faces in src/okie-thermo-fonts.js"
font_css = "".join(faces)

logic = (ROOT / "src/okie-logic.js").read_text(encoding="utf-8")
parts = []
parts.append(re.search(r"^  var ACTIVE = \{.*?\};$", logic, re.M).group(0))
parts.append(re.search(r"^  var RANGES = \{.*?\};$", logic, re.M).group(0))
parts.append(re.search(r"^  var LABELS = \{.*?^  \};$", logic, re.M | re.S).group(0))
for name in ["toSegments", "durationsByState", "isActive", "historyStats", "hourlyActivity", "fmtDuration", "stateLabel", "relativeTime"]:
    parts.append(function_source(logic, name))
logic_src = "\n".join(p.replace("\n  ", "\n") .lstrip() for p in parts)

thermo = (ROOT / "src/okie-thermo.js").read_text(encoding="utf-8")
look_parts = [re.search(r"^  var DEFAULT_LOOK = \{.*?\};$", thermo, re.M).group(0)]
for name in ["hexToRgb", "rgbToHex", "normalizeLook", "erf", "phi", "glowShape", "glowAlpha", "glowReach", "tickCount"]:
    look_parts.append(function_source(thermo, name))
look_src = "\n".join(p.replace("\n  ", "\n").lstrip() for p in look_parts)

sched = (ROOT / "src/okie-thermo-sched.js").read_text(encoding="utf-8")
m = re.search(r"// @pure:start[^\n]*\n(.*?)\n  // @pure:end", sched, re.S)
assert m, "the @pure:start / @pure:end block is missing in src/okie-thermo-sched.js"
sched_src = "\n".join(l[2:] if l.startswith("  ") else l for l in m.group(1).split("\n"))

page = (ROOT / "widget/big-page.html").read_text(encoding="utf-8")
for mark in ("/*@FONTS@*/", "/*@BOOT@*/", "/*@SHARED@*/", "/*@LOGIC@*/", "/*@SCHED@*/", "/*@LOOKSRC@*/"):
    assert page.count(mark) == 1, mark

path = ROOT / "widget/okie-thermostat-widget.js"
src = path.read_text(encoding="utf-8")
start, end = "// ---- generated by tools/make-widget.py, do not edit (fonts, the card's history code, the big page) ----", "// ---- end generated ----"
old_start = "// ---- fonts (generated by tools/make-widget.py, do not edit) ----"
import base64
tab_font = '@font-face{font-family:"Okie Sora Tab";font-style:normal;font-weight:600 800;src:url(data:font/woff2;base64,%s) format("woff2");}' % base64.b64encode((ROOT / "assets/fonts/Sora-tab.woff2").read_bytes()).decode()
block = "%s\nconst FONT_CSS = %s;\nconst TAB_FONT_CSS = %s;\nconst LOGIC_SRC = %s;\nconst SCHED_SRC = %s;\nconst LOOK_SRC = %s;\nconst BIG_PAGE = %s;\n%s" % (start, json.dumps(font_css), json.dumps(tab_font), json.dumps(logic_src), json.dumps(sched_src), json.dumps(look_src), json.dumps(page, ensure_ascii=False), end)
for s0 in (start, old_start):
    if s0 in src:
        e0 = end if s0 == start else "// ---- end fonts ----"
        a, b = src.index(s0), src.index(e0) + len(e0)
        src = src[:a] + block + src[b:]
        break
else:
    marker = "if (typeof Script !== 'undefined') await main();"
    assert marker in src
    src = src.replace(marker, block + "\n\n" + marker)
path.write_text(src, encoding="utf-8")
print("widget built: fonts %d bytes, history code %d bytes, schedule code %d bytes, look code %d bytes, page %d bytes; the script is %d bytes" % (len(font_css), len(logic_src), len(sched_src), len(look_src), len(page), len(src.encode("utf-8"))))


# ---- the weather widget: the pure code of the card's weather screen (icons, sky, rows, forecasts), cut out of src/okie-weather.js ----
wsrc = (ROOT / "src/okie-weather.js").read_text(encoding="utf-8")
m = re.search(r"// @pure:start[^\n]*\n(.*?)\n  // @pure:end", wsrc, re.S)
assert m, "the @pure:start / @pure:end block is missing in src/okie-weather.js"
pure = "\n".join(l[2:] if l.startswith("  ") else l for l in m.group(1).split("\n"))
wpath = ROOT / "widget/okie-weather-widget.js"
wtext = wpath.read_text(encoding="utf-8")
ws, we = "// ---- generated by tools/make-widget.py, do not edit (the pure code of src/okie-weather.js) ----", "// ---- end generated ----"
a, b = wtext.index(ws), wtext.index(we) + len(we)
wtext = wtext[:a] + ws + "\n" + pure + "\n" + we + wtext[b:]
wpath.write_text(wtext, encoding="utf-8")
print("weather widget built: the card's pure code %d bytes; the script is %d bytes" % (len(pure), len(wtext.encode("utf-8"))))


# ---- the feed widget: the two fonts it draws with (Manrope and the tabular Sora), as data ----
fpath = ROOT / "widget/okie-feed-widget.js"
ftext = fpath.read_text(encoding="utf-8")
fs0, fe0 = "// ---- generated by tools/make-widget.py, do not edit (the card's fonts as data) ----", "// ---- end generated ----"
a, b = ftext.index(fs0), ftext.index(fe0) + len(fe0)
manrope_b64 = base64.b64encode((ROOT / "assets/fonts/Manrope-latin.woff2").read_bytes()).decode()
sora_b64 = base64.b64encode((ROOT / "assets/fonts/Sora-tab.woff2").read_bytes()).decode()
ftext = ftext[:a] + fs0 + '\nconst MANROPE_B64 = %s;\nconst SORA_TAB_B64 = %s;\n' % (json.dumps(manrope_b64), json.dumps(sora_b64)) + fe0 + ftext[b:]
fpath.write_text(ftext, encoding="utf-8")
print("feed widget built: the script is %d bytes" % len(ftext.encode("utf-8")))


# ---- the shortcuts widget: the card's icons (flame, moon, sun, bulb) as they are in src/okie-ui.js, the shape code of the weather screen, and the font as data ----
import subprocess
icons = json.loads(subprocess.run(["node", "-e", "global.document={createElement(){return {}},addEventListener(){}};global.window=global;const U=require('./src/okie-ui.js');console.log(JSON.stringify(['flame','moon','sun','bulb'].reduce((o,n)=>(o[n]=U.ICONS[n],o),{})))"], cwd=str(ROOT), capture_output=True, text=True, check=True).stdout)
wsrc2 = (ROOT / "src/okie-weather.js").read_text(encoding="utf-8")
def wfunc(name):
    m = re.search(r"^  function %s\(" % re.escape(name), wsrc2, re.M)
    assert m, name
    i = wsrc2.index("{", m.start()); depth = 0
    for j in range(i, len(wsrc2)):
        if wsrc2[j] == "{": depth += 1
        elif wsrc2[j] == "}":
            depth -= 1
            if depth == 0:
                return "\n".join(l[2:] if l.startswith("  ") else l for l in wsrc2[m.start():j + 1].split("\n"))
icons['bulb3'] = '<path d="M12 2.4a6.4 6.4 0 0 0-3.9 11.5c.7.6 1.2 1.4 1.2 2.3v.5h5.4v-.5c0-.9.5-1.7 1.2-2.3A6.4 6.4 0 0 0 12 2.4z" data-fill/><path d="M9.1 19h5.8M10 21.1h4M11 23h2"/>'      # the wall tablet's bulb: a round bulb and three lines under it
shape_code = "\n".join(wfunc(n) for n in ["shapesOf", "arcToCurves", "parsePath"])
spath = ROOT / "widget/okie-shortcuts-widget.js"
stext = spath.read_text(encoding="utf-8")
ss, se = "// ---- generated by tools/make-widget.py, do not edit (the card's own icons and the shape code of the weather screen) ----", "// ---- end generated ----"
a, b = stext.index(ss), stext.index(se) + len(se)
stext = stext[:a] + ss + "\nconst ICON_INNER = " + json.dumps(icons) + ";\n" + shape_code + "\n" + se + stext[b:]
fs1, fe1 = "// ---- generated by tools/make-widget.py, do not edit (the card's fonts as data) ----", "// ---- end generated ----"
a, b = stext.index(fs1), stext.index(fe1, stext.index(fs1)) + len(fe1)
stext = stext[:a] + fs1 + "\nconst MANROPE_B64 = %s;\n" % json.dumps(base64.b64encode((ROOT / "assets/fonts/Manrope-latin.woff2").read_bytes()).decode()) + fe1 + stext[b:]
spath.write_text(stext, encoding="utf-8")
print("shortcuts widget built: the script is %d bytes" % len(stext.encode("utf-8")))
