#!/usr/bin/env python3
"""Write src/okie-thermo-fonts.js: Sora and Manrope (latin, variable) as data URIs, the fonts of the Thermo Dial project.

    python3 tools/make-thermo-fonts.py

The woff2 files in assets/fonts come from Google Fonts (css2 API, latin subset, variable weight axis). Both fonts are free under the
SIL Open Font License 1.1 (https://openfontlicense.org): Sora, Copyright 2019 The Sora Project Authors (github.com/sora-xor/sora-font);
Manrope, Copyright 2018 The Manrope Project Authors (github.com/sharanda/manrope). They are embedded so the card needs no request to
any font server and works offline.
"""
import base64
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = [("Okie Sora", "Sora-latin.woff2", "600 800"), ("Okie Manrope", "Manrope-latin.woff2", "500 800")]

faces = []
for family, fname, weight in FONTS:
    b64 = base64.b64encode((ROOT / "assets/fonts" / fname).read_bytes()).decode()
    faces.append('@font-face{font-family:"%s";font-style:normal;font-weight:%s;font-display:swap;src:url(data:font/woff2;base64,%s) format("woff2");}' % (family, weight, b64))

js = """/* okie-thermo-fonts: Sora (the big number) and Manrope (the labels), the fonts of the Thermo Dial project, embedded.
 *
 * Generated by tools/make-thermo-fonts.py from assets/fonts. Do not edit by hand.
 * Both fonts are free under the SIL Open Font License 1.1 (https://openfontlicense.org):
 *   Sora    Copyright 2019 The Sora Project Authors (https://github.com/sora-xor/sora-font)
 *   Manrope Copyright 2018 The Manrope Project Authors (https://github.com/sharanda/manrope)
 * The rules go into the page's <head>: a font declared inside a shadow tree is not reliably found by every browser, one declared in the
 * document is found by every card. The names are "Okie Sora" and "Okie Manrope", so nothing else on the page is touched.
 */
(function (g) {
  'use strict';
  var css = %s;
  if (typeof document === 'undefined') return;
  function install() {
    if (document.getElementById('okie-thermo-fonts')) return;
    var st = document.createElement('style'); st.id = 'okie-thermo-fonts'; st.textContent = css;
    (document.head || document.documentElement).appendChild(st);
  }
  install();
  g.OkieMotor = g.OkieMotor || {}; g.OkieMotor.thermoFonts = { install: install, CSS: css };
})(typeof globalThis !== 'undefined' ? globalThis : window);
""" % ("\n    + ".join(repr(f) if False else "'" + f.replace("\\", "\\\\").replace("'", "\\'") + "'" for f in faces))
(ROOT / "src/okie-thermo-fonts.js").write_text(js, encoding="utf-8")
print("wrote src/okie-thermo-fonts.js (%d KB)" % (len(js) // 1024))
